-- Guess pool genişlediği için botların rastgele çok teknik/özel guess kelimelerine
-- kaymasını önlemek amacıyla decoy seçiminde kontrollü A1 cevap havuzu kullanılır.
create or replace function public.pick_bot_decoy(
  p_match_id uuid,
  p_answer text,
  p_length integer,
  p_bot_key text
)
returns text
language plpgsql
security definer
volatile
set search_path = public, pg_temp
as $$
declare
  chosen text;
begin
  if lower(p_bot_key)='efe' then
    select w.word into chosen
    from public.multiplayer_answer_words w
    where w.answer_version='A1'
      and w.enabled=true
      and w.length=p_length
      and w.word<>p_answer
      and not exists(
        select 1 from public.bot_match_guesses g
        where g.match_id=p_match_id and g.actor='bot' and g.guess_word=w.word
      )
    order by random()
    limit 1;
  else
    select s.word into chosen
    from (
      select w.word
      from public.multiplayer_answer_words w
      where w.answer_version='A1'
        and w.enabled=true
        and w.length=p_length
        and w.word<>p_answer
        and not exists(
          select 1 from public.bot_match_guesses g
          where g.match_id=p_match_id and g.actor='bot' and g.guess_word=w.word
        )
      order by random()
      limit 140
    ) s
    order by (
      ((public.live_feedback(s.word,p_answer)->>'green')::integer
        * case when lower(p_bot_key)='atlas' then 4 else 3 end)
      + ((public.live_feedback(s.word,p_answer)->>'yellow')::integer
        * case when lower(p_bot_key)='atlas' then 2 else 1 end)
      + random()*case when lower(p_bot_key)='atlas' then 1.5 else 4 end
    ) desc
    limit 1;
  end if;

  if chosen is null then
    select w.word into chosen
    from public.multiplayer_guess_words w
    where w.length=p_length and w.word<>p_answer
    order by random()
    limit 1;
  end if;

  return chosen;
end;
$$;

revoke all on function public.pick_bot_decoy(uuid,text,integer,text) from public, anon, authenticated;
